        <h2>Project <span>Overview</span></h2>

        <p>
            The Tiles Management System simplifies daily business
            operations for tile and marble shops. It provides a
            centralized interface for handling customer accounts,
            product stock, invoice generation, payment collection,
            supplier purchases and business transactions.
        </p>

        <p>
            The application follows the CodeIgniter MVC structure
            and uses a MySQL database to organize business records.
        </p>

    </section>


