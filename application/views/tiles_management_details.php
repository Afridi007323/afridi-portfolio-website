                total billing, received payments and pending dues.
                View customer payment status and access transaction
                history through the customer directory.
            </p>
        </div>

        <!-- 3. Sales & Billing -->
        <div class="project-feature-card">
            <i class="fa-solid fa-file-invoice"></i>
            <h3>Sales & Billing</h3>
            <p>
                Create invoices by selecting customers and products,
                entering quantities and rates, and calculating bill
                totals. Track previous dues, new bills and payments
                during the billing process.
            </p>
        </div>

        <!-- 4. Inventory Management -->
        <div class="project-feature-card">
            <i class="fa-solid fa-boxes-stacked"></i>
            <h3>Inventory Management</h3>
            <p>
                Manage products with category-wise stock details,
                including tiles, marble, hardware and other items.
                Review product quantities, units and prices, and
                identify low-stock items.
            </p>
        </div>

        <!-- 5. Payments & Dues -->
        <div class="project-feature-card">
            <i class="fa-solid fa-wallet"></i>
            <h3>Payments & Dues</h3>
            <p>
                Record customer payments, check current outstanding
                balances and review completed payment records.
                Monitor invoice amounts and payment status.
            </p>
        </div>

        <!-- 6. Purchase Management -->
        <div class="project-feature-card">
            <i class="fa-solid fa-truck-ramp-box"></i>
            <h3>Purchase Management</h3>
            <p>
                Create supplier purchase entries, add products with
                quantities and rates, record paid amounts, and
                calculate remaining and total outstanding dues.
                Review purchase history and receipt records.
            </p>
        </div>

        <!-- 7. Invoice & Receipt -->
        <div class="project-feature-card">
            <i class="fa-solid fa-receipt"></i>
            <h3>Invoice & Receipt Management</h3>
            <p>
                Generate printable customer invoices containing
                business and customer details, item-wise totals,
                previous dues, total payable, paid amount and
                remaining balance. Print bills, share them through
                WhatsApp and download invoices as PDF.
            </p>
        </div>

    </div>

